import 'dart:convert';
import 'dart:io';

import 'package:gubasic_lang/gubasic_lang.dart';

/// The benchmarks of STAGE2_PLAN §7, each a project and the event script
/// that drives it: the projects in ../../test/bench/ with their
/// bench.events, and the typing and quiz examples with
/// ../../test/bench/typing.events and the quiz's parity script. Written to
/// lib/src/bench/projects.g.dart, which only the measuring builds import
/// (`package:gubasic_player/bench.dart`), so apps never carry it.
///
///     dart run tool/embed_bench.dart          # write the file
///     dart run tool/embed_bench.dart --check  # fail if out of date
void main(List<String> args) {
  final benches = <String, (Directory, File)>{
    for (final d in Directory(
      '../../test/bench',
    ).listSync().whereType<Directory>())
      _name(d.uri): (d, File('${d.path}/bench.events')),
    'typing': (
      Directory('../../examples/typing'),
      File('../../test/bench/typing.events'),
    ),
    'quiz': (
      Directory('../../examples/quiz'),
      File('../../test/parity/quiz_example.events'),
    ),
  };
  final names = benches.keys.toList()..sort();

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/embed_bench.dart from test/bench/ and')
    ..writeln('// examples/. Do not edit by hand.')
    ..writeln()
    ..writeln('/// Each benchmark\'s project files, by name.')
    ..writeln('const benchFiles = <String, Map<String, String>>{');
  for (final name in names) {
    final (dir, _) = benches[name]!;
    final files =
        dir
            .listSync()
            .whereType<File>()
            .where((f) => !f.path.endsWith('.events'))
            .toList()
          ..sort((a, b) => a.path.compareTo(b.path));
    out.writeln('  ${jsonEncode(name)}: {');
    for (final f in files) {
      out.writeln(
        '    ${jsonEncode(_name(f.uri))}: '
        '${jsonEncode(f.readAsStringSync().replaceAll('\r\n', '\n'))},',
      );
    }
    out.writeln('  },');
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln('/// Each benchmark\'s pictures: name → the bytes in Base64.')
    ..writeln('const benchPictures = <String, Map<String, String>>{');
  for (final name in names) {
    final (dir, _) = benches[name]!;
    final project = dir.listSync().whereType<File>().firstWhere(
      (f) => f.path.endsWith('.gbproj'),
    );
    final read = readProjectFile(project.readAsStringSync());
    if (read.hasErrors) {
      stderr.writeln('${project.path} has errors');
      exit(1);
    }
    out.writeln('  ${jsonEncode(name)}: {');
    for (final picture in read.project.pictures) {
      final bytes = File('${dir.path}/pictures/$picture').readAsBytesSync();
      out.writeln(
        '    ${jsonEncode(picture)}: ${jsonEncode(base64Encode(bytes))},',
      );
    }
    out.writeln('  },');
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln('/// Each benchmark\'s event script.')
    ..writeln('const benchScripts = <String, String>{');
  for (final name in names) {
    final (_, script) = benches[name]!;
    out.writeln(
      '  ${jsonEncode(name)}: '
      '${jsonEncode(script.readAsStringSync().replaceAll('\r\n', '\n'))},',
    );
  }
  out.writeln('};');

  final text = _formatted(out.toString().replaceAll(r'$', r'\$'));
  final target = File('lib/src/bench/projects.g.dart');
  if (args.contains('--check')) {
    if (!target.existsSync() || target.readAsStringSync() != text) {
      stderr.writeln(
        'lib/src/bench/projects.g.dart is out of date: '
        'run dart run tool/embed_bench.dart',
      );
      exit(1);
    }
    return;
  }
  target.writeAsStringSync(text);
}

String _name(Uri uri) => uri.pathSegments.where((s) => s.isNotEmpty).last;

/// [source] as `dart format` leaves it, formatted inside this package so
/// that its language version applies.
String _formatted(String source) {
  final dir = Directory('.dart_tool').createTempSync('bench');
  try {
    final file = File('${dir.path}/bench.dart')..writeAsStringSync(source);
    final r = Process.runSync(Platform.resolvedExecutable, [
      'format',
      file.path,
    ]);
    if (r.exitCode != 0) throw StateError('dart format failed: ${r.stderr}');
    return file.readAsStringSync();
  } finally {
    dir.deleteSync(recursive: true);
  }
}
