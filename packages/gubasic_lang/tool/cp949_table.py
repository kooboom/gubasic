"""Writes lib/src/text/cp949_table.dart: Microsoft's code page 949, the
"ANSI" text of Korean Windows, as Python's cp949 codec has it (D113).

Run from packages/gubasic_lang: python3 tool/cp949_table.py
The table does not change; it is kept with the source, not regenerated.
"""
lines = []
for lead in range(0x81, 0xFF):
    row = []
    for trail in range(0x41, 0xFF):
        try:
            ch = bytes([lead, trail]).decode('cp949')
        except UnicodeDecodeError:
            ch = '�'
        cp = ord(ch)
        if ch in ("'", '\\', '$') or cp < 0x20 or cp == 0x7f or 0x80 <= cp < 0xa0:
            row.append('\\u%04x' % cp)
        else:
            row.append(ch)
    lines.append("    '" + ''.join(row) + "'")
out = [
    '// GENERATED by tool/cp949_table.py from Python\'s cp949 codec (D113).',
    '// ignore_for_file: lines_longer_than_80_chars',
    '',
    '/// The characters of the two-byte codes of code page 949: row',
    '/// `lead - 0x81`, column `trail - 0x41`, 190 to a row; U+FFFD for a',
    '/// code that is none.',
    'const cp949Table =',
    '\n'.join(lines) + ';',
    '',
]
open('lib/src/text/cp949_table.dart', 'w', encoding='utf-8').write('\n'.join(out))
