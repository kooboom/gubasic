import 'dart:convert';
import 'dart:io';

/// Copies every ../../components/NAME/component.yaml into
/// lib/src/forms/components.g.dart, so that the analyzer knows the
/// built-in controls on every platform, the web included, where files
/// cannot be read.
///
///     dart run tool/embed_components.dart          # write the file
///     dart run tool/embed_components.dart --check  # fail if out of date
void main(List<String> args) {
  final files = Directory('../../components')
      .listSync()
      .whereType<Directory>()
      .map((d) => File('${d.path}/component.yaml'))
      .where((f) => f.existsSync())
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/embed_components.dart from components/.')
    ..writeln('// Do not edit by hand.')
    ..writeln()
    ..writeln('/// The text of each built-in component.yaml, by folder name.')
    ..writeln('const builtinComponentFiles = <String, String>{');
  for (final f in files) {
    final name = f.parent.uri.pathSegments.where((s) => s.isNotEmpty).last;
    out.writeln('  ${jsonEncode(name)}: ${jsonEncode(f.readAsStringSync())},');
  }
  out.writeln('};');

  final text = _formatted(out.toString().replaceAll(r'$', r'\$'));
  final target = File('lib/src/forms/components.g.dart');
  if (args.contains('--check')) {
    if (!target.existsSync() || target.readAsStringSync() != text) {
      stderr.writeln('lib/src/forms/components.g.dart is out of date: '
          'run dart run tool/embed_components.dart');
      exit(1);
    }
    return;
  }
  target.writeAsStringSync(text);
}

/// [source] as `dart format` leaves it, so that the format check in CI and
/// the --check above agree. Formatted inside this package, so that the
/// package's language version (and therefore its style) applies.
String _formatted(String source) {
  final dir = Directory('.dart_tool').createTempSync('components');
  try {
    final file = File('${dir.path}/components.dart')..writeAsStringSync(source);
    final r =
        Process.runSync(Platform.resolvedExecutable, ['format', file.path]);
    if (r.exitCode != 0) throw StateError('dart format failed: ${r.stderr}');
    return file.readAsStringSync();
  } finally {
    dir.deleteSync(recursive: true);
  }
}
