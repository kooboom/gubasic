import 'dart:convert';
import 'dart:io';

/// Copies every project in ../../examples/ into
/// lib/src/project/examples.g.dart, so that the IDE can open them on every
/// platform, the web included, where files cannot be read.
///
///     dart run tool/embed_examples.dart          # write the file
///     dart run tool/embed_examples.dart --check  # fail if out of date
void main(List<String> args) {
  final projects =
      Directory('../../examples').listSync().whereType<Directory>().toList()
        ..sort((a, b) => a.path.compareTo(b.path));

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/embed_examples.dart from examples/.')
    ..writeln('// Do not edit by hand.')
    ..writeln()
    ..writeln('/// The files of each example project, by folder name.')
    ..writeln('const exampleProjects = <String, Map<String, String>>{');
  for (final dir in projects) {
    final files = dir.listSync().whereType<File>().toList()
      ..sort((a, b) => a.path.compareTo(b.path));
    out.writeln('  ${jsonEncode(_name(dir.uri))}: {');
    for (final f in files) {
      final text = f.readAsStringSync().replaceAll('\r\n', '\n');
      out.writeln('    ${jsonEncode(_name(f.uri))}: ${jsonEncode(text)},');
    }
    out.writeln('  },');
  }
  out.writeln('};');

  final text = _formatted(out.toString().replaceAll(r'$', r'\$'));
  final target = File('lib/src/project/examples.g.dart');
  if (args.contains('--check')) {
    if (!target.existsSync() || target.readAsStringSync() != text) {
      stderr.writeln(
        'lib/src/project/examples.g.dart is out of date: '
        'run dart run tool/embed_examples.dart',
      );
      exit(1);
    }
    return;
  }
  target.writeAsStringSync(text);
}

String _name(Uri uri) => uri.pathSegments.where((s) => s.isNotEmpty).last;

/// [source] as `dart format` leaves it, so that the format check in CI and
/// the --check above agree. Formatted inside this package, so that the
/// package's language version (and therefore its style) applies.
String _formatted(String source) {
  final dir = Directory('.dart_tool').createTempSync('examples');
  try {
    final file = File('${dir.path}/examples.dart')..writeAsStringSync(source);
    final r = Process.runSync(Platform.resolvedExecutable, [
      'format',
      file.path,
    ]);
    if (r.exitCode != 0) throw StateError('dart format failed: ${r.stderr}');
    return file.readAsStringSync();
  } finally {
    dir.deleteSync(recursive: true);
  }
}
