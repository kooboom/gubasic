import 'dart:convert';
import 'dart:io';

/// Copies the parity programs (../../test/parity) into
/// test/parity_cases.g.dart, so that the same cases run in Chrome, where
/// tests cannot read files.
///
///     dart run tool/embed_parity.dart          # write the file
///     dart run tool/embed_parity.dart --check  # fail if it is out of date
void main(List<String> args) {
  final dir = Directory('../../test/parity');
  final programs = dir
      .listSync()
      .whereType<File>()
      .where((f) => f.path.endsWith('.gbas'))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  String? read(String path) {
    final f = File(path);
    return f.existsSync() ? f.readAsStringSync() : null;
  }

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/embed_parity.dart from test/parity/.')
    ..writeln('// Do not edit by hand.')
    ..writeln()
    ..writeln(
        '/// (name, program, InputBox answers, expected output, form file,')
    ..writeln('/// event script, saved settings); the form file and the event')
    ..writeln('/// script are null without a form, the settings without')
    ..writeln('/// NAME.settings.')
    ..writeln('const parityCases = <(String, String, List<String>, String, '
        'String?, String?, String?)>[');
  for (final p in programs) {
    final name = p.uri.pathSegments.last.replaceFirst('.gbas', '');
    final input = read(p.path.replaceFirst('.gbas', '.in'));
    final answers =
        input == null ? <String>[] : const LineSplitter().convert(input);
    out
      ..writeln('  (')
      ..writeln('    ${jsonEncode(name)},')
      ..writeln('    ${jsonEncode(p.readAsStringSync())},')
      ..writeln('    ${jsonEncode(answers)},')
      ..writeln(
          '    ${jsonEncode(read(p.path.replaceFirst('.gbas', '.out')) ?? '')},')
      ..writeln(
          '    ${jsonEncode(read(p.path.replaceFirst('.gbas', '.form.yaml')))},')
      ..writeln(
          '    ${jsonEncode(read(p.path.replaceFirst('.gbas', '.events')))},')
      ..writeln(
          '    ${jsonEncode(read(p.path.replaceFirst('.gbas', '.settings'))?.trim())},')
      ..writeln('  ),');
  }
  out.writeln('];');

  final text = _formatted(out.toString().replaceAll(r'$', r'\$'));
  final target = File('test/parity_cases.g.dart');
  if (args.contains('--check')) {
    if (!target.existsSync() || target.readAsStringSync() != text) {
      stderr.writeln('test/parity_cases.g.dart is out of date: '
          'run dart run tool/embed_parity.dart');
      exit(1);
    }
    return;
  }
  target.writeAsStringSync(text);
}

/// [source] as `dart format` leaves it, so that the format check in CI and
/// the --check above agree.
String _formatted(String source) {
  final dir = Directory.systemTemp.createTempSync('parity');
  try {
    final file = File('${dir.path}/cases.dart')..writeAsStringSync(source);
    // Outside the package the formatter would take the newest language
    // version; the package's (pubspec.yaml) gives what `dart format .` does.
    final r = Process.runSync(Platform.resolvedExecutable,
        ['format', '--language-version=3.5', file.path]);
    if (r.exitCode != 0) throw StateError('dart format failed: ${r.stderr}');
    return file.readAsStringSync();
  } finally {
    dir.deleteSync(recursive: true);
  }
}
